"""Builds the Bayonetta 2 Archipelago launcher (ap/launcher/ap_launcher.c) with B2recomp's toolchain (llvm-mingw).

    python ap/tools/build_launcher.py [--out=<exe>]

Default output: "Bayonetta 2 Archipelago.exe" at the top of the project (beside B2recomp/ and ap/). The Archipelago
logo (ap/assets/ap_logo.png) becomes the window's picture (a generated header, premultiplied BGRA) and the program's
icon; nothing of the game is used. Generated files go to ap/launcher/build/.
"""
import os
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AP = os.path.dirname(HERE)
ROOT = os.path.dirname(AP)
B2 = os.path.join(ROOT, 'B2recomp')
sys.path.insert(0, os.path.join(B2, 'scripts'))
import toolchain  # noqa: E402
from PIL import Image  # noqa: E402

SRC = os.path.join(AP, 'launcher')
GEN = os.path.join(SRC, 'build')
OUT = next((os.path.abspath(a[6:]) for a in sys.argv[1:] if a.startswith('--out=')),
           os.path.join(ROOT, 'Bayonetta 2 Archipelago.exe'))
os.makedirs(GEN, exist_ok=True)

logo = Image.open(os.path.join(AP, 'assets', 'ap_logo.png')).convert('RGBA')
px = bytearray()
raw = logo.tobytes()
for i in range(0, len(raw), 4):                       # premultiplied BGRA for AlphaBlend
    r, g, b, a = raw[i:i + 4]
    px += bytes((b * a // 255, g * a // 255, r * a // 255, a))
with open(os.path.join(GEN, 'ap_logo.h'), 'w') as f:
    f.write('/* generated by ap/tools/build_launcher.py from ap/assets/ap_logo.png */\n')
    f.write('#define AP_LOGO_W %d\n#define AP_LOGO_H %d\n' % logo.size)
    f.write('static const unsigned char ap_logo[%d] = {\n' % len(px))
    for i in range(0, len(px), 24):
        f.write('  ' + ','.join(str(v) for v in px[i:i + 24]) + ',\n')
    f.write('};\n')

side = max(logo.size)                                 # the icon: the logo on a square canvas
sq = Image.new('RGBA', (side, side), (0, 0, 0, 0))
sq.paste(logo, ((side - logo.width) // 2, (side - logo.height) // 2))
ico = os.path.join(GEN, 'ap_launcher.ico')
sq.resize((256, 256), Image.LANCZOS).save(ico, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])

rc, res = os.path.join(GEN, 'ap_launcher.rc'), os.path.join(GEN, 'ap_launcher.res')
with open(rc, 'w') as f:
    f.write('1 24 "%s"\n' % os.path.join(SRC, 'ap_launcher.manifest').replace('\\', '/'))
    f.write('1 ICON "%s"\n' % ico.replace('\\', '/'))


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    return r.returncode


code = run([toolchain.LLVM_RC, '/fo', res, rc])
if not code:
    target = ['-municode', '-mwindows', res] if toolchain.MINGW else ['-Wl,/subsystem:windows', '-Xlinker', res]
    code = run([toolchain.CLANG, '-O2', '-Wall', '-Wno-missing-braces', '-D_CRT_SECURE_NO_WARNINGS', '-I', GEN,
                os.path.join(SRC, 'ap_launcher.c'), '-o', OUT, '-luser32', '-lgdi32', '-lcomctl32', '-lshell32', '-ldwmapi',
                '-lmsimg32', '-lole32', '-luuid', '-ladvapi32', '-lcomdlg32'] + target)
print('%s: exit %d (TOOLCHAIN=%s)' % (OUT, code, toolchain.NAME))
sys.exit(code)
