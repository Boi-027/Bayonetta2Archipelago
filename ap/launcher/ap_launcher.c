/* ================================================================ pictures
 * Premultiplied BGRA images; every size and tint drawn is made once (area average when smaller, bilinear when larger)
 * and kept, so the window can be redrawn 30 times a second for its animations. */
typedef struct { int w, h; const unsigned char *px; } Img;
static Img im_logo, im_art, im_seal, im_moon, im_font, im_ap;
static int g_glyph_h, g_gx[128], g_gw[128];          /* the menu font: row height; x and width per character (0 = none) */

static int load_bmp(Img *im, const wchar_t *dir, const wchar_t *name) {
    wchar_t p[MAX_PATH];
    swprintf(p, MAX_PATH, L"%s\\%s", dir, name);
    FILE *f = _wfopen(p, L"rb");
    if (!f) return 0;
    BITMAPFILEHEADER fh; BITMAPINFOHEADER ih;
    int ok = fread(&fh, sizeof fh, 1, f) == 1 && fread(&ih, sizeof ih, 1, f) == 1 && fh.bfType == 0x4d42 && ih.biBitCount == 32 && ih.biHeight < 0;
    if (ok) {
        size_t n = (size_t)ih.biWidth * (size_t)(-ih.biHeight) * 4;
        unsigned char *px = malloc(n);
        fseek(f, (long)fh.bfOffBits, SEEK_SET);
        if (px && fread(px, 1, n, f) == n) { im->w = ih.biWidth; im->h = -ih.biHeight; im->px = px; }
        else { free(px); ok = 0; }
    }
    fclose(f);
    return ok;
}
