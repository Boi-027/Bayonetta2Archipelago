    SetEnvironmentVariableW(L"PYTHONIOENCODING", L"utf-8"); SetEnvironmentVariableW(L"PYTHONUNBUFFERED", L"1");
    SetEnvironmentVariableW(L"PYTHONNOUSERSITE", L"1");
