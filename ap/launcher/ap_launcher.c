static void banner(HDC dc, RECT r, int id, const wchar_t *label, int style, int enabled) {   /* style 0 blue, 1 gold, 2 red */
    float t = enabled ? hov(H_BTN, id, 0) : 0;
    int pressed = g_press >= 0 && g_press < g_nhit && g_hit[g_press].kind == H_BTN && g_hit[g_press].id == id;
    COLORREF band = style == 1 ? mix(C_GOLD_D, C_GOLD, 0.55f + 0.45f * t) : style == 2 ? mix(RGB(110, 24, 44), RGB(170, 40, 64), t) : mix(RGB(20, 64, 132), C_BLUE, t);
    int a = enabled ? (style == 1 ? 235 : 150 + (int)(80 * t)) : 60;
    if (pressed) a = a * 3 / 4;
    strip(dc, r, band, 1, a);
    COLORREF edge = style == 1 ? RGB(255, 236, 170) : style == 2 ? C_RED : C_LINE_HI;
    hline(dc, r.left, r.top, r.right - r.left, edge, enabled ? 140 + (int)(100 * t) : 50);
    hline(dc, r.left, r.bottom - 1, r.right - r.left, edge, enabled ? 140 + (int)(100 * t) : 50);
    int h = (r.bottom - r.top) * 44 / 100;
    COLORREF tc = !enabled ? C_DIM : style == 1 ? RGB(46, 30, 4) : style == 2 ? RGB(255, 210, 216) : mix(C_TEXT, RGB(255, 255, 255), t);
    gtext_c(dc, r, h, tc, 255, label);
    hit(r, H_BTN, id, 0, enabled);
}
