static int install_progress(void) {                    /* per mille of the whole install */
    int total = 0, done = 0;
    for (int j = 0; j < J_COUNT; j++) {
        if (g_job_state[j] == 4) continue;
        total += k_job_weight[j];
        if (g_job_state[j] == 2) done += k_job_weight[j];
        else if (g_job_state[j] == 1 && j == J_GAME) {
            /* setup.py's steps: compile (step 7 of 10) is most of it */
            static const int w[10] = { 1, 2, 1, 1, 2, 11, 240, 1, 8, 2 };
            int all = 0, d = 0;
            for (int k = 0; k < 10; k++) { all += w[k]; if (k < g_game_step - 1) d += w[k]; }
            if (g_game_step == 7) d += w[6] * g_compile / 1000;
            done += k_job_weight[j] * d / all;
        }
    }
    return total ? done * 1000 / total : 0;
}
static void compile_progress(void) {                  /* the last "[a/b]" of B2recomp\build\logs\compile.log */
    if (g_job != J_GAME || g_game_step != 7) return;
    wchar_t p[MAX_PATH];
    pathf(p, L"%s\\build\\logs\\compile.log", g_b2);
    HANDLE h = CreateFileW(p, GENERIC_READ, FILE_SHARE_READ | FILE_SHARE_WRITE | FILE_SHARE_DELETE, NULL, OPEN_EXISTING, 0, NULL);
    if (h == INVALID_HANDLE_VALUE) return;
    LARGE_INTEGER sz, off; char b[512]; DWORD got = 0;
    GetFileSizeEx(h, &sz);
    off.QuadPart = sz.QuadPart > 511 ? sz.QuadPart - 511 : 0;
    SetFilePointerEx(h, off, NULL, FILE_BEGIN);
    ReadFile(h, b, 511, &got, NULL);
    CloseHandle(h);
    b[got] = 0;
    char *q = NULL;
    for (char *s = b; (s = strstr(s, "\n[")) != NULL; s++) q = s + 1;
    int a, n;
    if (q && sscanf(q, "[%d/%d]", &a, &n) == 2 && n > 0 && a <= n) g_compile = a * 1000 / n;
}
