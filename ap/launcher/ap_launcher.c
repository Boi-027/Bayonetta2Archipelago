static int text_w(HDC dc, HFONT f, const wchar_t *t) { SIZE s; SelectObject(dc, f); GetTextExtentPoint32W(dc, t, (int)wcslen(t), &s); return s.cx; }
static COLORREF mix(COLORREF a, COLORREF b, float t) {
    if (t < 0) t = 0;
    if (t > 1) t = 1;
    return RGB((int)(GetRValue(a) + (GetRValue(b) - GetRValue(a)) * t), (int)(GetGValue(a) + (GetGValue(b) - GetGValue(a)) * t),
               (int)(GetBValue(a) + (GetBValue(b) - GetBValue(a)) * t));
}

/* ================================================================ the game's menu font
 * Capitals only (the game's title menu has no J, Q, V, Z and no digits: those come from a serif); O is the game's
 * stylised one, as in its own menus. h: device pixels of the letters' box. */
static HFONT serif_at(int h) {
    static struct { int h; HFONT f; } cache[12];
    static int n;
    for (int i = 0; i < n; i++) if (cache[i].h == h) return cache[i].f;
    if (n == 12) return cache[11].f;                  /* (a handful of sizes are used) */
    LOGFONTW lf = { 0 };
    lf.lfHeight = -(h * 7 / 10); lf.lfWeight = FW_BOLD; lf.lfQuality = CLEARTYPE_QUALITY;
    wcscpy(lf.lfFaceName, L"Palatino Linotype");
    HFONT f = CreateFontIndirectW(&lf);
    if (n < 12) cache[n++] = (typeof(cache[0])){ h, f };
    return f;
}
static int gchar(wchar_t c) {
    if (c >= L'a' && c <= L'z') c -= 32;
    if (c == L'O') c = L'o';
    return c < 128 && g_gw[c] ? c : 0;
}
static int gtext_w(HDC dc, int h, const wchar_t *t) {
    int w = 0;
    float k = g_glyph_h ? (float)h / g_glyph_h : 0;
    for (const wchar_t *p = t; *p; p++) {
        if (*p == L' ') { w += h * 42 / 100; continue; }
        int g = im_font.px ? gchar(*p) : 0;
        if (g) w += (int)(g_gw[g] * k) + h * 14 / 100;
        else { wchar_t s[2] = { (wchar_t)towupper(*p), 0 }; w += text_w(dc, serif_at(h), s) + h / 10; }
    }
    return w;
}
static void gtext(HDC dc, int x, int y, int h, COLORREF c, int alpha, const wchar_t *t) {
    float k = g_glyph_h ? (float)h / g_glyph_h : 0;
    c = RGB(GetRValue(c) & 0xf0, GetGValue(c) & 0xf0, GetBValue(c) & 0xf0);
    HBITMAP atlas = im_font.px ? scaled(&im_font, 0, 0, im_font.w, im_font.h, (int)(im_font.w * k), h, c) : NULL;
    for (const wchar_t *p = t; *p; p++) {
        if (*p == L' ') { x += h * 42 / 100; continue; }
        int g = atlas ? gchar(*p) : 0;
        if (g) {
            int gx = (int)(g_gx[g] * k), gw = (int)(g_gw[g] * k);
            blend(dc, atlas, x, y, gw, h, gx, 0, gw, h, alpha);
            x += gw + h * 14 / 100;
        } else {                                      /* a letter the menu font lacks */
            wchar_t s[2] = { (wchar_t)towupper(*p), 0 };
            SelectObject(dc, serif_at(h)); SetTextColor(dc, c); SetBkMode(dc, TRANSPARENT);
            TextOutW(dc, x, y + h * 12 / 100, s, 1);
            x += text_w(dc, serif_at(h), s) + h / 10;
        }
    }
}
static void gtext_glow(HDC dc, int x, int y, int h, COLORREF c, COLORREF glow, float amount, const wchar_t *t) {
    if (amount > 0.02f) {
        static const int off[8][2] = { {-2,0},{2,0},{0,-2},{0,2},{-1,-1},{1,1},{-1,1},{1,-1} };
        for (int i = 0; i < 8; i++) gtext(dc, x + S(off[i][0]), y + S(off[i][1]), h, glow, (int)(55 * amount), t);
    }
    gtext(dc, x, y, h, c, 255, t);
}
static void gtext_c(HDC dc, RECT r, int h, COLORREF c, int alpha, const wchar_t *t) {   /* centred in r */
    int w = gtext_w(dc, h, t);
    gtext(dc, (r.left + r.right - w) / 2, (r.top + r.bottom - h) / 2, h, c, alpha, t);
}

