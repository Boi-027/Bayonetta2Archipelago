    for (int i = 0; i < g_nhov; i++) if (g_hov[i].kind == kind && g_hov[i].id == id && g_hov[i].sub == sub) return g_hov[i].t;
    if (g_nhov < 96) g_hov[g_nhov++] = (Hov){ kind, id, sub, 0 };
