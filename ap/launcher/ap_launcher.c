typedef struct { const Img *src; int sx, sy, sw, sh, w, h; COLORREF tint; HBITMAP bm; } Scaled;
static Scaled g_cache[64];
static int g_ncache;
static HBITMAP scaled(const Img *s, int sx, int sy, int sw, int sh, int w, int h, COLORREF tint) {   /* tint 0xffffffff: as is */
    for (int i = 0; i < g_ncache; i++) {
        Scaled *c = &g_cache[i];
        if (c->src == s && c->sx == sx && c->sy == sy && c->sw == sw && c->sh == sh && c->w == w && c->h == h && c->tint == tint) return c->bm;
    }
    if (!s->px || w <= 0 || h <= 0 || w > 4096 || h > 4096) return NULL;
    BITMAPINFO bi = { { sizeof(BITMAPINFOHEADER), w, -h, 1, 32, BI_RGB } };
    unsigned char *d = NULL;
    HBITMAP bm = CreateDIBSection(NULL, &bi, DIB_RGB_COLORS, (void **)&d, NULL, 0);
    if (!bm || !d) return NULL;
    float kx = (float)sw / w, ky = (float)sh / h;
    for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) {
        float acc[4] = { 0, 0, 0, 0 };
        if (kx > 1 || ky > 1) {                       /* smaller: the average of the box under the pixel */
            int x0 = sx + (int)(x * kx), x1 = sx + (int)((x + 1) * kx), y0 = sy + (int)(y * ky), y1 = sy + (int)((y + 1) * ky);
            if (x1 <= x0) x1 = x0 + 1;
            if (y1 <= y0) y1 = y0 + 1;
            int n = 0;
            for (int yy = y0; yy < y1 && yy < s->h; yy++) for (int xx = x0; xx < x1 && xx < s->w; xx++, n++) {
                const unsigned char *q = s->px + ((size_t)yy * s->w + xx) * 4;
                acc[0] += q[0]; acc[1] += q[1]; acc[2] += q[2]; acc[3] += q[3];
            }
            if (n) for (int c = 0; c < 4; c++) acc[c] /= n;
        } else {                                      /* larger: bilinear */
            float fx = sx + (x + 0.5f) * kx - 0.5f, fy = sy + (y + 0.5f) * ky - 0.5f;
            if (fx < sx) fx = (float)sx;
            if (fy < sy) fy = (float)sy;
            int x0 = (int)fx, y0 = (int)fy, x1 = x0 + 1 < sx + sw ? x0 + 1 : x0, y1 = y0 + 1 < sy + sh ? y0 + 1 : y0;
            float ax = fx - x0, ay = fy - y0;
            for (int c = 0; c < 4; c++) {
                float a = s->px[((size_t)y0 * s->w + x0) * 4 + c] * (1 - ax) + s->px[((size_t)y0 * s->w + x1) * 4 + c] * ax;
                float b = s->px[((size_t)y1 * s->w + x0) * 4 + c] * (1 - ax) + s->px[((size_t)y1 * s->w + x1) * 4 + c] * ax;
                acc[c] = a * (1 - ay) + b * ay;
            }
        }
        unsigned char *o = d + ((size_t)y * w + x) * 4;
        if (tint != 0xffffffff) {                     /* the picture's brightness times the colour */
            float lum = (acc[0] + acc[1] + acc[2]) / (3 * 255.0f);
            o[0] = (unsigned char)(GetBValue(tint) * lum); o[1] = (unsigned char)(GetGValue(tint) * lum); o[2] = (unsigned char)(GetRValue(tint) * lum);
        } else { o[0] = (unsigned char)acc[0]; o[1] = (unsigned char)acc[1]; o[2] = (unsigned char)acc[2]; }
        o[3] = (unsigned char)acc[3];
    }
    if (g_ncache == 64) { DeleteObject(g_cache[0].bm); memmove(g_cache, g_cache + 1, 63 * sizeof *g_cache); g_ncache--; }
    g_cache[g_ncache++] = (Scaled){ s, sx, sy, sw, sh, w, h, tint, bm };
    return bm;
}
static HBITMAP faded(HBITMAP src, int w, int h) {    /* a copy whose alpha falls off to the bottom and the left */
    static HBITMAP out; static HBITMAP from; static int ow, oh;
    if (out && from == src && ow == w && oh == h) return out;
    if (!src) return NULL;
    BITMAPINFO bi = { { sizeof(BITMAPINFOHEADER), w, -h, 1, 32, BI_RGB } };
    unsigned char *d;
    if (out) DeleteObject(out);
    out = CreateDIBSection(NULL, &bi, DIB_RGB_COLORS, (void **)&d, NULL, 0);
    DIBSECTION ds; GetObjectW(src, sizeof ds, &ds);
    const unsigned char *sp = ds.dsBm.bmBits;
    for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) {
        float fy = (float)(h - 1 - y) / (h * 0.55f), fx = (float)x / (w * 0.16f), fr = (float)(w - 1 - x) / (w * 0.05f);
        float a = (fy < 1 ? fy : 1) * (fx < 1 ? fx : 1) * (fr < 1 ? fr : 1);
        a = a * a * (3 - 2 * a);
        for (int k = 0; k < 4; k++) d[((size_t)y * w + x) * 4 + k] = (unsigned char)(sp[((size_t)y * w + x) * 4 + k] * a);
    }
    from = src; ow = w; oh = h;
    return out;
}
static void blend(HDC dc, HBITMAP bm, int x, int y, int w, int h, int sx, int sy, int sw, int sh, int alpha) {
    if (!bm || alpha <= 0) return;
    HDC m = CreateCompatibleDC(dc);
    HGDIOBJ o = SelectObject(m, bm);
    BLENDFUNCTION bf = { AC_SRC_OVER, 0, (BYTE)(alpha > 255 ? 255 : alpha), AC_SRC_ALPHA };
    AlphaBlend(dc, x, y, w, h, m, sx, sy, sw, sh, bf);
    SelectObject(m, o); DeleteDC(m);
}
static void draw_img(HDC dc, const Img *im, int x, int y, int w, int h, int alpha, COLORREF tint) {
    blend(dc, scaled(im, 0, 0, im->w, im->h, w, h, tint), x, y, w, h, 0, 0, w, h, alpha);
}

